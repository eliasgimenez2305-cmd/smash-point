-- Planes, etapa 3: publicidades atadas a su cliente de la plataforma y contador de clics.
--
-- - publicidades_ocultas(): los ids de las publicidades cuyo cliente (tipo publicidad, ref_id = id del
--   anuncio) está vencido, suspendido o dado de baja. La página pública no las muestra; vuelven solas
--   cuando el creador registra el cobro. (La vigencia desde/hasta de cada anuncio la controla la app.)
-- - publicidad_clics: un renglón por cada vez que alguien toca una publicidad. Lo anota contar_clic()
--   (lo puede llamar cualquiera, sin sesión); solo el creador ve los números (clics_publicidades()).
--
-- Se corre una vez en Supabase > SQL Editor, después de 20261034_planes_en_la_app.sql.
-- Prueba: supabase/pruebas/publicidades.sql (solo en el proyecto de PRUEBA). Vuelta atrás: al final.

create or replace function public.publicidades_ocultas()
returns setof text
language sql
stable
security definer
set search_path = public
as $$
  select c.ref_id from plataforma_clientes c
  where c.tipo = 'publicidad' and c.ref_id is not null
    and (not c.activo or public.plan_estado(c) in ('vencido', 'suspendido'));
$$;

revoke all on function public.publicidades_ocultas() from public;
grant execute on function public.publicidades_ocultas() to anon, authenticated;

create table if not exists public.publicidad_clics (
  id bigint generated by default as identity primary key,
  ad_id text not null check (char_length(ad_id) between 1 and 60),
  created_at timestamptz not null default now()
);
create index if not exists publicidad_clics_por_ad on public.publicidad_clics (ad_id, created_at);

alter table public.publicidad_clics enable row level security;
revoke all on public.publicidad_clics from public, anon, authenticated;
grant select on public.publicidad_clics to authenticated;
drop policy if exists "Solo el creador ve los clics" on public.publicidad_clics;
create policy "Solo el creador ve los clics" on public.publicidad_clics for select to authenticated using (public.es_creador());

-- Anota un clic (sin sesión). Un id raro o vacío se ignora.
create or replace function public.contar_clic(p_ad text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_ad is null or char_length(p_ad) not between 1 and 60 then
    return;
  end if;
  insert into publicidad_clics (ad_id) values (p_ad);
end;
$$;

revoke all on function public.contar_clic(text) from public;
grant execute on function public.contar_clic(text) to anon, authenticated;

-- Clics de cada publicidad: en total y desde una fecha (el mes en curso, en el panel). Solo el creador.
create or replace function public.clics_publicidades(p_desde date)
returns table (ad_id text, total bigint, desde bigint)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.es_creador() then
    raise exception 'no_autorizado';
  end if;
  return query
    select k.ad_id, count(*), count(*) filter (where (k.created_at at time zone 'America/Argentina/Buenos_Aires')::date >= p_desde)
    from publicidad_clics k
    group by k.ad_id;
end;
$$;

revoke all on function public.clics_publicidades(date) from public, anon;
grant execute on function public.clics_publicidades(date) to authenticated;

